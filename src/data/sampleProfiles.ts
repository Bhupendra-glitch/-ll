function generateDailyForecast(baseDaily: number, variance: number, count: number) {
  const points = [];
  const now = new Date();
  for (let i = 1; i <= count; i++) {
    const d = new Date(now);
    d.setDate(d.getDate() + i);
    const dayOfWeek = d.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6; // Weekend surge for gig
    const weekendMultiplier = isWeekend ? 1.35 : 1.0;
    const p50 = Math.round(baseDaily * weekendMultiplier * (1 + (Math.sin(i / 3.5) * 0.12)));
    const p10 = Math.round(p50 * 0.78); // Downside risk
    const p90 = Math.round(p50 * 1.32); // Peak surge

    points.push({
      dayIndex: i,
      date: d.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' }),
      p10,
      p50,
      p90,
      eventNote: isWeekend ? 'Weekend Surge' : (i % 14 === 0 ? 'Bi-weekly Platform Bonus' : undefined),
    });
  }
  return points;
}

